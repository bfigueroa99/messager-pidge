#!/usr/bin/env node
/**
 * `pnpm run seed:cities` (M1-03) generates `supabase/migrations/0009_seed_cities.sql`
 * from `apps/mobile/src/data/cities.json`, the single source of truth for the
 * bundled cities dataset — the same JSON the client's search index reads
 * directly (see `apps/mobile/src/data/cities.ts`), so the server and the
 * offline client never disagree about what a city is.
 *
 * Migrations are forward-only and committed, not generated at deploy time —
 * this script's output is checked in. Run with `--check` (what
 * `tests/cities-seed.test.ts` exercises under `pnpm run verify`) to fail
 * instead of overwriting if the committed migration has drifted from the
 * source JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_PATH = join(rootDir, 'apps/mobile/src/data/cities.json');
const OUTPUT_PATH = join(rootDir, 'supabase/migrations/0009_seed_cities.sql');

function sqlString(value) {
  if (value === null) return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  if (!Number.isFinite(value)) {
    throw new Error(`not a finite number: ${value}`);
  }
  return String(value);
}

export function generateCitiesSql(cities) {
  const rows = cities
    .map(
      ([id, name, admin1, countryCode, lat, lon, population]) =>
        `  (${sqlString(id)}, ${sqlString(name)}, ${sqlString(admin1)}, ${sqlString(countryCode)}, ` +
        `${sqlNumber(lat)}, ${sqlNumber(lon)}, ${sqlNumber(population)})`,
    )
    .join(',\n');

  return `-- ─────────────────────────────────────────────────────────────────────────────
-- 0009 — seed the bundled cities dataset (M1-03)
--
-- GENERATED by \`pnpm run seed:cities\` from apps/mobile/src/data/cities.json —
-- do not edit by hand. See scripts/generate-cities-seed.mjs.
--
-- A curated, real-world subset (not a literal GeoNames extract — this
-- container has no network access to fetch one; see docs/JOURNAL.md). Public
-- read via the \`cities_read\` policy (0003_rls.sql). Every stored profile
-- location is snapped to one of these centroids by \`snap_profile_location()\`
-- (0001_init.sql, 0008_loft_snap_fixes.sql), which is what enforces INV-7.
--
-- Forward-only. Never edit a migration that has been merged; add a new one.
-- ─────────────────────────────────────────────────────────────────────────────

insert into cities (id, name, admin1, country_code, lat, lon, population)
values
${rows};
`;
}

function main() {
  const cities = JSON.parse(readFileSync(SOURCE_PATH, 'utf8'));
  const generated = generateCitiesSql(cities);
  const check = process.argv.includes('--check');

  if (check) {
    const committed = readFileSync(OUTPUT_PATH, 'utf8');
    if (committed !== generated) {
      console.error(
        `${OUTPUT_PATH} is out of date with ${SOURCE_PATH}. Run \`pnpm run seed:cities\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log('supabase/migrations/0009_seed_cities.sql is up to date.');
    return;
  }

  writeFileSync(OUTPUT_PATH, generated);
  console.log(`Wrote ${OUTPUT_PATH} (${cities.length} cities).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
